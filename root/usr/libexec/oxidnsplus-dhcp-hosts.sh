#
# Learn local hostnames from the official OpenWrt dnsmasq lease file and write
# a standard hosts file for OxiDNS's hosts_system(format: standard) plugin.
#
# Official OpenWrt dnsmasq.init hardcodes:
#     --dhcp-leasefile /tmp/dhcp.leases
# Record format: <expiry_epoch> <MAC> <IPv4> <hostname> <client_id>
# hostname may be "*" when the client did not advertise one.
#
# The file is only replaced when its content actually changes. A config
# reload is only attempted when something changed AND it is requested,
# because reload can drop cache entries newer than the last cache.dump.

uci_get() {
	if command -v uci >/dev/null 2>&1; then
		uci -q get "oxidnsplus.main.$1" 2>/dev/null || printf '%s' "$2"
	else
		printf '%s' "$2"
	fi
}

LEASE_FILE="$(uci_get lease_file '/tmp/dhcp.leases')"
OUT="$(uci_get hosts_output '/etc/oxidns/dhcp-hosts')"
DOMAIN="$(uci_get lease_domain 'lan')"
AUTO_RELOAD="$(uci_get dhcp_auto_reload '0')"
RELOAD_MODE="$(uci_get reload_mode 'signal')"
STATE_FILE="/tmp/oxidnsplus-dhcp.state"

FORCE_RELOAD=0
[ "${1:-}" = "--reload" ] && FORCE_RELOAD=1

log() {
	logger -t oxidns-plus "$1" 2>/dev/null || true
}

write_state() {
	_tmp="$STATE_FILE.tmp.$$"
	{
		printf 'last_run=%s\n' "$(date '+%Y-%m-%d %H:%M:%S' 2>/dev/null || printf unknown)"
		printf 'leases=%s\n' "${1:-0}"
		printf 'changed=%s\n' "${2:-0}"
		printf 'reload=%s\n' "${3:-unknown}"
		printf 'rc=%s\n' "${4:-1}"
	} > "$_tmp" && mv "$_tmp" "$STATE_FILE" || rm -f "$_tmp"
}

if [ ! -r "$LEASE_FILE" ]; then
	log "dhcp: lease file $LEASE_FILE not readable"
	write_state 0 0 "lease_missing" 1
	echo "dhcp: lease file $LEASE_FILE not readable" >&2
	exit 1
fi

case "$DOMAIN" in
	*[!A-Za-z0-9.-]*|'') DOMAIN="lan" ;;
esac

mkdir -p "$(dirname "$OUT")" 2>/dev/null || true
TMP="$OUT.tmp.$$"

# Fixed header (no timestamp) so cmp -s is a real content comparison.
{
	printf '# Generated by luci-app-oxidns-plus from %s. Do not edit by hand.\n' "$LEASE_FILE"
	awk -v domain="$DOMAIN" '
		NF >= 4 {
			ip = $3; host = $4;
			if (host == "" || host == "*" || host == "-") next;
			if (ip !~ /^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$/) next;
			gsub(/[^A-Za-z0-9-]/, "", host);
			if (host == "" || seen[host]++) next;
			printf "%s %s.%s %s\n", ip, host, domain, host;
		}
	' "$LEASE_FILE"
} > "$TMP" || {
	rm -f "$TMP"
	write_state 0 0 "generate_failed" 1
	exit 1
}

leases=$(awk 'NR > 1 { n++ } END { print n + 0 }' "$TMP")

changed=0
if [ ! -f "$OUT" ] || ! cmp -s "$OUT" "$TMP"; then
	mv "$TMP" "$OUT" || { rm -f "$TMP"; exit 1; }
	chmod 644 "$OUT" 2>/dev/null || true
	changed=1
else
	rm -f "$TMP"
fi

reload_result="not_requested"
if [ "$changed" = "1" ]; then
	if [ "$FORCE_RELOAD" = "1" ] || [ "$AUTO_RELOAD" = "1" ]; then
		if [ -x /etc/init.d/oxidns ]; then
			if [ "$RELOAD_MODE" = "restart" ]; then
				if /etc/init.d/oxidns restart >/dev/null 2>&1; then
					reload_result="restarted"
				else
					reload_result="failed"
				fi
			else
				if /etc/init.d/oxidns reload >/dev/null 2>&1; then
					reload_result="signaled"
				else
					reload_result="failed"
				fi
			fi
		else
			reload_result="init_missing"
		fi
	else
		reload_result="pending_manual"
	fi
else
	reload_result="unchanged"
fi

log "dhcp: leases=$leases changed=$changed reload=$reload_result"
echo "dhcp: leases=$leases changed=$changed reload=$reload_result"

if [ "$reload_result" = "failed" ] || [ "$reload_result" = "init_missing" ]; then
	write_state "$leases" "$changed" "$reload_result" 1
	exit 1
fi
write_state "$leases" "$changed" "$reload_result" 0
exit 0
